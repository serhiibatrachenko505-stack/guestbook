-- V1: початкова схема БД — книги, користувачі, відгуки та зовнішні ключі

CREATE TABLE books (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title     VARCHAR(255) NOT NULL,
    author    VARCHAR(255) NOT NULL,
    pub_year  INT          NOT NULL
);

CREATE TABLE users (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username  VARCHAR(64)  NOT NULL,
    password  VARCHAR(255),
    role      VARCHAR(32)  NOT NULL DEFAULT 'USER',
    CONSTRAINT uq_users_username UNIQUE (username)
);

CREATE TABLE comments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id     BIGINT        NOT NULL,
    user_id     BIGINT,
    author      VARCHAR(64)   NOT NULL,
    text        VARCHAR(1000) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- видалення книги видаляє її відгуки
    CONSTRAINT fk_comments_book FOREIGN KEY (book_id) REFERENCES books (id) ON DELETE CASCADE,
    -- видалення користувача залишає його відгуки (user_id стає NULL)
    CONSTRAINT fk_comments_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_comments_book ON comments (book_id, created_at);
CREATE INDEX idx_comments_user ON comments (user_id, created_at);
