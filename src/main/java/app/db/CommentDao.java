package app.db;

import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/** Об'єкт доступу до даних таблиці comments. */
public class CommentDao {

  /** Створює таблицю, якщо її ще немає (стандартний синтаксис identity). */
  public void init() throws SQLException {
    try (var c = Db.get(); var st = c.createStatement()) {
      st.execute("""
          create table if not exists comments(
            id         bigint generated by default as identity primary key,
            author     varchar(64)   not null,
            text       varchar(1000) not null,
            created_at timestamp     not null default current_timestamp
          )""");
    }
  }

  /** Додає коментар і повертає згенерований id. */
  public long add(String author, String text) throws SQLException {
    try (var c = Db.get();
         var ps = c.prepareStatement(
             "insert into comments(author, text) values(?, ?)",
             Statement.RETURN_GENERATED_KEYS)) {
      ps.setString(1, author);
      ps.setString(2, text);
      ps.executeUpdate();
      try (var keys = ps.getGeneratedKeys()) {
        return keys.next() ? keys.getLong(1) : -1L;
      }
    }
  }

  /** Повертає всі коментарі, найновіші — першими. */
  public List<Map<String, Object>> list() throws SQLException {
    try (var c = Db.get();
         var ps = c.prepareStatement(
             "select id, author, text, created_at from comments order by id desc");
         var rs = ps.executeQuery()) {
      var out = new ArrayList<Map<String, Object>>();
      while (rs.next()) {
        Map<String, Object> row = new LinkedHashMap<>();
        row.put("id", rs.getLong("id"));
        row.put("author", rs.getString("author"));
        row.put("text", rs.getString("text"));
        row.put("createdAt", rs.getTimestamp("created_at").toInstant().toString());
        out.add(row);
      }
      return out;
    }
  }
}
